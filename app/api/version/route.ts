import { NextResponse } from "next/server";
import { buildId } from "@/lib/buildId";

export const dynamic = "force-dynamic";

/**
 * รหัสของ build ที่กำลังให้บริการอยู่
 *
 * แอปบนมือถือเป็น WebView ที่ไม่โหลดหน้าใหม่เมื่อเปิดจากรายการแอปล่าสุด — หน้าเดิม
 * ยังอยู่ในหน่วยความจำ JavaScript ตัวเก่าจึงทำงานต่อไปเรื่อย ๆ ผลคือแก้บั๊กฝั่ง
 * หน้าจอไปแล้วแต่ผู้ใช้ยังเจออาการเดิม (ส่วนที่แก้ฝั่งเซิร์ฟเวอร์หายไปแล้ว จึงยิ่ง
 * สับสนว่าอันไหนแก้แล้วอันไหนยัง) เกิดขึ้นจริงหลายรอบในวันเดียว
 *
 * หน้าเว็บเทียบค่านี้กับตอนที่มันโหลดมา ถ้าไม่ตรงคือมี build ใหม่ แล้วโหลดตัวเอง
 * ใหม่ในจังหวะที่ปลอดภัย (ตอนผู้ใช้กลับมาเห็นหน้าจอ)
 */
export async function GET() {
  return NextResponse.json(
    { build: buildId() },
    { headers: { "Cache-Control": "no-store, max-age=0" } }
  );
}
