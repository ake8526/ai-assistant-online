/**
 * ข้อความเดียวที่สั่งสองเรื่อง — แยก "ดูงานที่ต้องติดตาม" ออกจากคำสั่งอื่น
 *
 * เคสจริงที่พัง: ผู้ใช้ส่ง "ตารางวันนี้ แล้วดูงานที่ต้องติดตามด้วย"
 * ตัวจับวลีรายการงานผูกกับข้อความทั้งก้อน (^...$) จึงไม่ match แล้วเรื่องไปตกที่
 * เส้นทางหาตารางของคน ซึ่งเอา "งานที่ต้องติดตาม" ไปตีเป็นชื่อคน ตอบกลับว่า
 * "ยังหา งานที่ ตาม ไม่เจอในไดเรกทอรี" — ไม่ได้ตอบทั้งสองเรื่องที่ถาม
 *
 * ไฟล์นี้ทำแค่งานกับสตริง ไม่ import อะไร เพื่อให้ทดสอบแยกได้
 */

/** วลีที่หมายถึง "ขอดูรายการงานที่ค้าง" */
const TASK_LIST =
  /(?:ดู|ขอดู|เช็ค|ขอ)?\s*(?:งานที่ต้องติดตาม|งานที่ยังไม่ปิด|งานที่ค้าง|งานค้าง|รายการเตือน|รายการงาน)/;

/** คำที่บอกว่าประโยคนี้ "จัดการ" งาน ไม่ใช่ "ขอดู" — ห้ามแยก */
const TASK_ACTION = /(?:ปิด|เสร็จ|เคลียร์|ลบ|เพิ่ม|สร้าง|บันทึก|จด|แก้|เลื่อน)\s*(?:งาน|ทั้งหมด)/;

/** คำเชื่อม/คำหางที่เหลือค้างหลังตัดวลีออก ไม่ใช่เนื้อคำสั่ง */
const GLUE =
  /^(?:แล้ว|และ|กับ|ทั้ง|อีก|ต่อ|ด้วย|ช่วย|ขอ|เอา|ที|นะ|น่ะ|หน่อย|ครับ|ค่ะ|คะ|จ้า|ๆ|[\s,.;:!?และ])+$/;

/** ตัดคำเชื่อมหัวท้ายของท่อนที่เหลือ */
function trimGlue(s: string): string {
  let out = s.replace(/\s+/g, " ").trim();
  const lead = /^(?:แล้ว|และ|กับ|อีก|ต่อ|ด้วย|ช่วย|ขอ|เอา|ที)\s*/;
  const tail = /\s*(?:ด้วย|อีก|ต่อ|นะ|น่ะ|หน่อย|ครับ|ค่ะ|คะ|จ้า|เลย|แล้ว|และ|กับ)$/;
  let changed = true;
  while (changed) {
    changed = false;
    const a = out.replace(lead, "");
    if (a !== out) {
      out = a.trim();
      changed = true;
    }
    const b = out.replace(tail, "");
    if (b !== out) {
      out = b.trim();
      changed = true;
    }
  }
  return out.replace(/^[\s,.;:!?-]+|[\s,.;:!?-]+$/g, "").trim();
}

/**
 * คืนคำสั่งอีกเรื่องที่อยู่ในข้อความเดียวกัน หรือ null ถ้าไม่ใช่เคสนี้
 *
 * คืน null เมื่อ:
 *  - ไม่มีวลีรายการงานอยู่เลย
 *  - ข้อความเป็นวลีรายการงานอย่างเดียว (ทางเดิมจับได้อยู่แล้ว)
 *  - เป็นประโยคสั่ง "จัดการ" งาน เช่น ปิดงานทั้งหมด / เพิ่มงาน — ห้ามแยก
 *  - ท่อนที่เหลือสั้นเกินจะเป็นคำสั่ง
 */
export function splitTaskListAside(raw: string): { rest: string } | null {
  const text = String(raw || "").replace(/\s+/g, " ").trim();
  if (!text) return null;
  if (TASK_ACTION.test(text)) return null;

  const m = TASK_LIST.exec(text);
  if (!m) return null;

  const rest = trimGlue(text.slice(0, m.index) + " " + text.slice(m.index + m[0].length));
  if (!rest || GLUE.test(rest) || rest.length < 3) return null;

  return { rest };
}
